#!/usr/bin/env python3
"""
Regenerate data/sqlite/media_data.sql and data/postgresql/media_data.sql from
data/mysql/media_data.sql.

The MySQL file is the source. Its string literals use MySQL's backslash
escapes (\\n, \\r, \\t, \\0, \\Z, \\', \\", \\\\). Neither SQLite nor PostgreSQL
(with standard_conforming_strings, the default) interprets those, so every
literal is decoded to the value MySQL would store and written again in the
target dialect:

  SQLite      'text' with '' for a quote; control characters are spliced in
              with char(N), e.g. 'a' || char(10) || 'b'.
  PostgreSQL  'text' with '' for a quote; a literal that holds a backslash or
              a control character is written as an E'' string with \\n, \\r,
              \\t and \\\\ escapes.

Each statement stays on one line, because the installer splits the file on a
semicolon at the end of a line (DbBasedInstaller::runQueriesFromFile()).

Usage:
  python3 data/convert_media_data_sql.py           # rewrite both files
  python3 data/convert_media_data_sql.py --check   # exit 1 if they are stale
"""

import sys
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent
SOURCE = DATA_DIR / 'mysql' / 'media_data.sql'
HEADER = ['-- Auto-generated by convert_media_data_sql.py', '-- Do not edit by hand.']

MYSQL_ESCAPES = {
    '0': '\0', "'": "'", '"': '"', 'b': '\b', 'n': '\n', 'r': '\r',
    't': '\t', 'Z': '\x1a', '\\': '\\',
    # MySQL keeps the backslash for \% and \_ (they only matter in LIKE).
    '%': '\\%', '_': '\\_',
}


def tokenize(statement):
    """Yield ('sql', text) and ('str', decoded value) parts of a MySQL statement."""
    out = []
    buf = []
    i = 0
    n = len(statement)
    while i < n:
        ch = statement[i]
        if ch == '`':
            j = statement.index('`', i + 1)
            buf.append('"' + statement[i + 1:j] + '"')
            i = j + 1
            continue
        if ch != "'":
            buf.append(ch)
            i += 1
            continue
        if buf:
            out.append(('sql', ''.join(buf)))
            buf = []
        i += 1
        value = []
        while True:
            if i >= n:
                raise ValueError('unterminated string literal: ' + statement[:120])
            ch = statement[i]
            if ch == '\\':
                nxt = statement[i + 1]
                value.append(MYSQL_ESCAPES.get(nxt, nxt))
                i += 2
            elif ch == "'":
                if i + 1 < n and statement[i + 1] == "'":
                    value.append("'")
                    i += 2
                else:
                    i += 1
                    break
            else:
                value.append(ch)
                i += 1
        out.append(('str', ''.join(value)))
    if buf:
        out.append(('sql', ''.join(buf)))
    return out


def is_control(ch):
    return ord(ch) < 32 or ord(ch) == 127


def sqlite_literal(value):
    if not any(is_control(c) for c in value):
        return "'" + value.replace("'", "''") + "'"
    parts = []
    chunk = []
    for c in value:
        if is_control(c):
            if chunk:
                parts.append("'" + ''.join(chunk).replace("'", "''") + "'")
                chunk = []
            parts.append('char(%d)' % ord(c))
        else:
            chunk.append(c)
    if chunk:
        parts.append("'" + ''.join(chunk).replace("'", "''") + "'")
    return '(' + ' || '.join(parts) + ')'


def pg_literal(value):
    if '\0' in value:
        raise ValueError('PostgreSQL text cannot hold NUL')
    if not any(is_control(c) or c == '\\' for c in value):
        return "'" + value.replace("'", "''") + "'"
    named = {'\n': '\\n', '\r': '\\r', '\t': '\\t', '\b': '\\b', '\f': '\\f', '\\': '\\\\', "'": "''"}
    body = ''.join(named.get(c, '\\x%02x' % ord(c) if is_control(c) else c) for c in value)
    return "E'" + body + "'"


def convert(source_text, dbms):
    literal = sqlite_literal if dbms == 'sqlite' else pg_literal
    lines = list(HEADER)
    if dbms == 'sqlite':
        lines += ['', 'PRAGMA foreign_keys = OFF;']
    for line in source_text.split('\n'):
        if line in HEADER or line.startswith('SET FOREIGN_KEY_CHECKS'):
            continue
        if not line.startswith('INSERT'):
            lines.append(line)
            continue
        parts = tokenize(line)
        lines.append(''.join(text if kind == 'sql' else literal(text) for kind, text in parts))
    return '\n'.join(lines)


def main(argv):
    check = '--check' in argv
    source_text = SOURCE.read_text(encoding='utf-8')
    stale = []
    for dbms in ('sqlite', 'postgresql'):
        target = DATA_DIR / dbms / 'media_data.sql'
        content = convert(source_text, dbms)
        current = target.read_text(encoding='utf-8') if target.exists() else None
        if current == content:
            print('PASS %s is current' % target.relative_to(DATA_DIR.parent))
            continue
        if check:
            stale.append(target)
            print('FAIL %s is stale' % target.relative_to(DATA_DIR.parent))
            continue
        target.write_text(content, encoding='utf-8')
        print('WROTE %s' % target.relative_to(DATA_DIR.parent))
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
